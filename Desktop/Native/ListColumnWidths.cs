namespace ApifoxHelper.Desktop.Native;

/// <summary>
/// 清单列宽的单一落点（docs/DESIGN.md §6「列表行」的列宽那一格）。
/// <para>
/// <b>为什么要有这个文件</b>：同一批条目在几张清单上装的是同一族内容，列宽却各写一遍——
/// 「标注」在注释缺口是 60px、在注释候选是 70px、在生成文档核对是 110px；「位置（说明点）」360 对 340；
/// 「文件:行」320 对 330；「资源」260 对 240。没有一份出处说明这些数为什么不同，于是每加一屏就再发明
/// 一个数，而用户读的是同一族文字。第二百零五轮收的是「同一类信息的<b>字体</b>由谁设」
/// （<c>Ui.CountCell</c> / <c>Ui.IdentityCell</c>），这一处收的是「同一类信息的<b>宽度</b>由谁给」。
/// </para>
/// <para>
/// <b>按内容族给宽，不按表头名给</b>：同名不等于同族。「审阅状态」在候选那一屏最长是「证据已变化」五字、
/// 在契约那一屏最长是三字；「分支」在配置那一侧是分支名、在契约清单里是分支数；「接口」「状态」
/// 「名称」「更新时间」都各有两族内容。按名字折会把某一屏那一格的真实内容挤掉——所以这里登记的是族，
/// 调用方在 <c>Columns.Add</c> 处说清这一格装的是哪一族，宽度不在此处按字符串猜。
/// </para>
/// <para>
/// <b>这些数怎么来的</b>（第二百四十二轮 <c>RunListColumnFit</c> 在 wine 96 档逐屏量真实控件，不是估的）：
/// ① 排序之后表头文字要连方向标记一起放下——「标注 ▲」「角色 ▲」量到 54px，加表头左右留白 12px
/// 是 66px，而注释缺口那一屏这两列当时都是 60px，<b>点一次列头就把自己的表头截掉</b>；
/// ② 一屏五列的合计不得超过「清单可视宽减一条竖向滚动条」的预算——注释缺口那一张清单可视宽 958px、
/// 滚动条 17px，预算 941px，其中未登记的「状态」列占 110px，四族可用 831px；
/// ③ 各族的内容长度按那一屏自己的取法量（样例见冒烟段）：「文件:行」298px、「资源」235px 放得下，
/// 「标注」带长参数名是 162px、<b>三屏哪一个数都装不下</b>。
/// 于是取法是：一族一个数，先满足 ① 的下界，再在最紧的那一屏（注释缺口）满足 ②，
/// 内容真的超过 ③ 的那一族把全文交给详情区那一行（<see cref="SlotText.TagDetailLine"/>），
/// 而不是把宽度加到谁也装不满的宽度。
/// </para>
/// <para>
/// <b>代价记在这里</b>：「标注」60 → 110（注释缺口、注释候选两屏各加 50 / 40px，排序后表头不再自截）、
/// 「角色」60 → 70（同一屏，同一原因）；「位置（说明点）」360 / 340 → 320（两屏各减 40 / 20px，
/// 那是这一屏唯一被减的一族，符号全文本来就在详情区第一行「符号：」里）；「文件:行」330 → 320
/// （代码证据那一屏减 10px，298px 的样例仍放得下）；「资源」260 → 240（差异确认那一屏减 20px，
/// 235px 的样例仍放得下）。真机上这些格的实际截断位置随 G-D5 复核。
/// </para>
/// <para>
/// <b>本轮未扩面（不是漏掉）</b>：只登记「同一族出现在两张以上清单」与「被 ① 的下界顶到」的那些列。
/// 一屏独用、且没有跨屏同名族的其他列（各清单的说明列、详情列、时间列）仍留在各屏自己那一句里——
/// 把它们一并搬进来等于给一个没有第二个用户的数字造一个词汇表。这一条由用例钉住不许被顺手「统一」掉。
/// </para>
/// <para>
/// <b>这一文件只管水平轴</b>（屏级契约，与 <see cref="SyncPreviewPanes"/> 各管一半，第二百四十四轮）：
/// 这里给的每一格都是<b>列宽</b>；那一屏里凡是高度（窗体高、块高、块开销）都归
/// <c>SyncPreviewPanes</c>，这里一个都不写，反过来那边也不写宽。两轴分开是因为挤没主清单那一发
/// 正是「同一个数在几处各写一遍」凑出来的——多一处就地像素数，就多用一次「算式与判据各说各的」。
/// 这一条由 <c>SyncPreviewPanesTests.TheTwoAxes_NeverWriteEachOthersNumber</c> 判（两边源文里
/// 不得出现对方的口径名），不新增任何行为。
/// </para>
/// </summary>
public static class ListColumnWidths
{
    /// <summary>
    /// 注释位置那一格（清单表头写「位置（说明点）」，注释缺口与注释候选两屏同一族内容）。
    /// 96 档量到的样例「GET /api/probe」是 108px；真实符号显示名更长，超出部分在详情区第一行读全。
    /// </summary>
    public const int SlotLocation = 320;

    /// <summary>
    /// 标注那一格（说明 / 返回 / 参数 + 参数名）：注释缺口、注释候选、生成文档核对三屏同一族。
    /// 下界由排序后的表头给出（54 + 12 = 66px），三屏现读数是 60 / 70 / 110，取其中最大的那一个。
    /// </summary>
    public const int SlotTag = 110;

    /// <summary>角色那一格（接口 / 请求 / 响应 / 枚举）：内容两字就够，但排序后的表头「角色 ▲」要 66px。</summary>
    public const int SlotRole = 70;

    /// <summary>「文件:行」那一格（注释缺口与代码证据两屏同一族）：96 档量到的样例 298px。</summary>
    public const int FileLine = 320;

    /// <summary>
    /// 资源身份那一格（「GET /路径」与模型名）：差异确认、同步预览写入清单、未纳入清单三屏同一族。
    /// 96 档量到的样例 235px；同步预览那两屏的合计最紧（写入清单 984px 对预算 1001px），故取 240 不取 260。
    /// </summary>
    public const int ResourceKey = 240;

    /// <summary>
    /// 排序之后的表头最少要给的那一段宽（px）：本轮量到「标注 ▲」「角色 ▲」文字 54px、
    /// 表头左右留白 12px。任何一族的新值都不得低过它——低了就是点一次列头把自己的表头截掉。
    /// </summary>
    public const int SortedHeaderFloor = 66;
}
