namespace ApifoxHelper.Desktop.Native;

/// <summary>
/// 同步预览「未纳入计划」清单的口径（DESIGN.md §6「列表筛选」，第八十六轮）：
/// 关键词匹配的是那一行在屏幕上被读作的那两格——资源与未纳入原因。
/// 这一屏没有筛选下拉（未纳入原因是逐条结果、不是可选状态），故走只有关键词框的那一支。
/// 不依赖 WinForms，以共享源码编入测试工程在 Linux 断言。
///
/// 缺口：同一个预览页的写入清单自第八十轮起就有关键词框、未纳入清单没有——而这一张往往比写入清单更长：
/// 计划只纳入需要写入的接口与模型，其余全部落在这里（「无需修改」「检查之后远端已被修改」
/// 「引用的模型存在阻断项」…），真实项目里几十上百条，要找到「上次那个接口为什么没进计划」只能逐行扫。
/// 同一个动作（在长清单里按关键词找一行）在别处有、在这一处没有，属同壳不同行为。
/// </summary>
public static class ExclusionEntries
{
    /// <summary>
    /// 一行未纳入条目在关键词里能被找到的那两格：资源（接口身份或 <c>model:名称</c>）与未纳入原因。
    /// 顺序与清单两列一致（资源 | 未纳入原因），界面不另造一套字段。
    /// 原因进关键词是这一屏的要害：用户问的正是「为什么没进计划」，而答案就在这一格里。
    /// </summary>
    public static string?[] KeywordFields(string resourceKey, string reason) => [resourceKey, reason];
}
