namespace ApifoxHelper.Desktop.Native;

/// <summary>
/// 状态行「查看完整错误」入口的口径（不依赖 WinForms，以共享源码编入测试工程在 Linux 断言）。
/// <para>
/// <b>为什么要有这个文件</b>：第一百五十九轮给状态行开了 <c>AutoEllipsis</c>——超长错误原因
/// 不再被静默裁掉，末尾出现「…」，WinForms 的 <c>Label</c> 还会把全文放进悬停提示。但悬停提示
/// 只解决「有下文」这一半：它要鼠标停住才出现、键盘用户拿不到、文字不可选中也不可复制，
/// 而状态行装的是 <c>Exception.Message</c>（.NET 的英文句子带文件全路径，动辄两三百字符），
/// 用户真正要做的是把这句话读全、必要时抄给同事或贴进工单。第一百六十二轮把这一处如实挂账为
/// 「状态行截断后的『查看完整错误』入口」，本轮补上。
/// </para>
/// <para>
/// <b>什么时候给入口</b>：只有文字真的放不下时才给。放得下还给一颗「查看完整错误」，
/// 点开看到的是同一句话——那是给用户添一步空动作（与 DESIGN.md §7「禁用不得移除下一步」
/// 同侧：入口要么指向用户拿不到的东西，要么不该出现）。判定只看两个数：文字首选宽度与
/// 「入口不占位时这一行的宽度」，界面层负责量，本文件只负责判。
/// </para>
/// <para>
/// <b>为什么两个方向都收敛</b>：入口出现会把状态行挤窄（按钮占去右侧一段）。如果判定拿挤窄后的
/// 宽度作基准，就会变成「出现 → 挤窄 → 更放不下 → 一直挂着」——入口替自己投票，短句也收不起来
/// （wine 实测到的正是这一支）。收敛的条件因此不在本文件的判据上，而在<b>基准的取法</b>上：
/// 界面层给进来的可用宽度必须是「入口不占位时这一行有多宽」，与入口此刻可见与否无关。
/// 这样同一句文字在两个状态下量到同一个数，判据本身又是单调的（文字在宽处放不下，在窄处必然
/// 也放不下），放得下与放不下才各自是稳定点。本文件只判这两个数的大小，不猜宽度从哪来——
/// 基准取错了在这里判不出来，由冒烟的真实交互拦住。
/// </para>
/// </summary>
public static class StatusLineText
{
    /// <summary>入口按钮的文字（全仓唯一落点：界面不就地拼写）。</summary>
    public const string FullTextButton = "查看完整错误";

    /// <summary>完整错误对话框的标题：说这一屏是什么，不说机制。</summary>
    public const string FullTextHeading = "完整错误信息";

    /// <summary>
    /// 完整错误对话框的说明行：讲清这块框能做什么（选中复制）与关掉之后回到哪一步。
    /// 不写「请联系管理员」这类没有落点的话——下一步在用户手里那颗「重试」上。
    /// </summary>
    public const string FullTextNote = "可以选中上面的文字复制；关闭后回到原处，按「重试」再读一次。";

    /// <summary>
    /// 状态行是否该给「查看完整错误」入口：文字首选宽度超过可用宽度才给。
    /// <para>
    /// <b>可用宽度 = 入口不占位时这一行有多宽</b>（宿主客户区宽减状态行左右留白），
    /// 不是标签当前宽度——标签当前宽度在入口出现后已经被按钮挤窄，拿它作基准会让入口替自己投票。
    /// </para>
    /// <para>
    /// 可用宽度为 0 或负数（控件还没布局、被折叠）时一律不给——那时「放不下」不是文字太长，
    /// 是这一行还没有宽度，给入口等于把布局时序当成内容问题（与 <c>ListReveal</c>
    /// 「序号越界一律不动作」同一取舍：宁可少给一次，不猜）。
    /// </para>
    /// </summary>
    public static bool ShouldOfferFullText(int preferredWidth, int availableWidth) =>
        availableWidth > 0 && preferredWidth > availableWidth;
}
