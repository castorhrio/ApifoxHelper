namespace ApifoxHelper.Desktop.Native;

/// <summary>
/// 注释回写两张清单的列排序键（DESIGN.md §6「列表列排序」，第一百零五、一百零八轮）：
/// 两个主页面（第四十七轮）、检查结果的两张清单（第九十七轮）、接口追踪明细（第九十八轮）、
/// 差异确认的条目清单（第九十九轮）、注释候选的候选清单（第一百轮）、响应契约的契约清单（第一百零一轮）、
/// 注释缺口清单（第一百零二轮）、生成文档核对的条目清单（第一百零三轮）与任务日志的记录清单（第一百零四轮）
/// 点击列头即按该列排序（同一列再点反向、换一列从升序开始、表头带方向标记），
/// 而注释回写的两张清单点击列头没有任何反应——文件清单（源码文件、回写范围、注释处数、回写结果四列，
/// 第一百零五轮）与跳过清单（跳过的位置、原因两列，第一百零八轮）。
/// 文件清单是整份计划的源码文件（真实项目一个模块几十个文件），
/// 「把只导出补丁的那几个集中看」「按注释处数排」「把已回写与未写入的分开」只能逐行扫；
/// 跳过清单是整份计划里没能生成修改的注释位置（每个被跳过的候选一行，真实项目几十条），
/// 而这一屏的说明行写着「跳过的位置（原因如下；处理后重新生成计划）」——
/// 要按原因处理就得先把同一原因的集中看，此前只能逐行扫。
/// 同一个动作在别处有、在这一处没有，属同壳不同行为。
/// 排序状态、方向翻转与表头标记仍取 <see cref="ListSort"/> 那一份（本文件只给「这一列按什么排」），
/// 界面不就地写 switch、不就地拼排序键——排序键与单元格取值同源，避免「显示与排序两套口径」。
/// 键的取法与单元格一致：源码文件列取路径原文（与首格同一份）、回写范围列取
/// <see cref="ApplyPlanEntries.ScopeText"/>（与第二格同一份）、注释处数列取处数本身并按数值排
/// （与两个主页面的数量列同一口径，按文字排会把「10」排到「2」前）、回写结果列取
/// <see cref="TaskDisplay.FileApplyStateText"/>（与第四格同一份中文映射；还没有结果时那一格是空串，
/// 排序键也交空串——空串在升序里排在最前，与「还没回写」这一屏的读法一致）；
/// 跳过清单两格取原文（位置与原因就是那两格的文字，原因进排序键正是这一屏的要害）。
/// 不依赖 WinForms，以共享源码编入测试工程在 Linux 断言。
/// </summary>
public static class ApplyPlanSort
{
    /// <summary>
    /// 文件清单的排序键（与建列顺序一一对应：源码文件、回写范围、注释处数、回写结果）。
    /// 四个参数就是这一行在屏幕上被读作的那四格——调用方传单元格的同一份取值，不另算一套。
    /// 列号落在建列之外交 null——与 <see cref="ListSort.Order"/> 的「缺键视为最小」同一处理，
    /// 不索引不存在的列、也不把邻列的值当成这一列。
    /// </summary>
    public static IComparable? Key(string relativePath, string scopeText, int edits, string resultText, int column) => column switch
    {
        0 => relativePath,
        1 => scopeText,
        2 => edits,
        3 => resultText,
        _ => null,
    };

    /// <summary>
    /// 跳过清单的排序键（与建列顺序一一对应：跳过的位置、原因）。
    /// 两个参数就是这一行在屏幕上被读作的那两格——调用方传单元格的同一份取值，不另算一套。
    /// 列号落在建列之外交 null（同上：不索引不存在的列、不把邻列的值当成这一列）。
    /// </summary>
    public static IComparable? SkippedKey(string display, string reason, int column) => column switch
    {
        0 => display,
        1 => reason,
        _ => null,
    };
}
