namespace ApifoxHelper.Desktop.Native;

/// <summary>
/// 两个主页面的名字（第二百五十七轮，具名 pass：clarify）：导航按钮、菜单项与「请到某一页去做某件事」
/// 的引导文案共用这一份。
/// <para>
/// <b>补的是哪个缺口</b>：首程（一台什么都没装的机器上第一次打开）这一屏的下一步全靠一句话指路——
/// 任务页空态说「先在「项目设置」新建配置」、没有配置时点「新建任务」的状态行说「请先在「项目设置」新建配置」、
/// 响应契约与接口追踪的提示说「请在项目设置中填写…」。这些句子指名的那个地方，就是侧栏上那颗按钮。
/// 而按钮文字此前是 <c>NavButton("项目设置")</c> 就地写的一串字面量，引导文案里又是另一串字面量：
/// <b>改一处不改另一处，界面就会指着一个不存在的页面</b>——与第四十六轮「文字不指向不存在的按钮」、
/// 第五十轮「提示所指引的恢复路径不可达」是同一族，只是这次指向的是页面而不是按钮。
/// </para>
/// <para>
/// <b>这一份是什么</b>：纯数据（不依赖 WinForms，与测试工程共享编译）。两个常量就是两个页面的名字，
/// 侧栏按钮、菜单项与全部引导文案都从这里取；名字要改就改这一处，改完由
/// <c>ApifoxHelper.Tests/PageNamesTests.cs</c> 判「界面与文案都跟着走了」。
/// </para>
/// <para>
/// <b>它不判什么</b>：不判「这句话该不该指这一页」——那是产品判断，只有人读得出来。
/// 也不判页面键（<see cref="LastPageKeys"/> 那一族）：页面键是落盘的值，与给人看的名字是两件事，
/// 改名字不该让上次停留的页面失效。
/// </para>
/// </summary>
public static class PageNames
{
    /// <summary>项目设置页（配置列表、新建/编辑配置、连接与写入探测）。</summary>
    public const string Projects = "项目设置";

    /// <summary>检查任务页（任务列表、任务详情与全部阶段动作）。</summary>
    public const string Tasks = "检查任务";
}
